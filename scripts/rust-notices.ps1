#Requires -Version 5.1
param([string]$Output = '')

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
if (-not $Output) { $Output = Join-Path $root 'licenses\rust-crates.txt' }
$cargo = Join-Path $env:USERPROFILE '.cargo\bin\cargo.exe'
if (-not (Test-Path $cargo)) { $cargo = 'cargo' }

$manifest = Join-Path $root 'launcher\Cargo.toml'
$json = & $cargo metadata --manifest-path $manifest --format-version 1 --filter-platform x86_64-pc-windows-msvc --locked
if ($LASTEXITCODE -ne 0) { throw 'cargo metadata failed.' }
$metadata = $json | ConvertFrom-Json

$packages = @{}
foreach ($package in $metadata.packages) { $packages[$package.id] = $package }
$nodes = @{}
foreach ($node in $metadata.resolve.nodes) { $nodes[$node.id] = $node }

$used = New-Object 'System.Collections.Generic.HashSet[string]'
$queue = New-Object 'System.Collections.Generic.Queue[string]'
$queue.Enqueue($metadata.resolve.root)
while ($queue.Count -gt 0) {
  $id = $queue.Dequeue()
  if (-not $used.Add($id)) { continue }
  foreach ($dependency in $nodes[$id].deps) {
    $normal = @($dependency.dep_kinds | Where-Object { $null -eq $_.kind -or $_.kind -eq 'normal' })
    if ($normal.Count -gt 0) { $queue.Enqueue($dependency.pkg) }
  }
}

$text = New-Object System.Text.StringBuilder
[void]$text.AppendLine('Rust crates compiled into stellaria-launcher.exe')
[void]$text.AppendLine('Generated by scripts/rust-notices.ps1 from launcher/Cargo.lock.')
[void]$text.AppendLine('')
$crates = $used | Where-Object { $_ -ne $metadata.resolve.root } | ForEach-Object { $packages[$_] } | Sort-Object name, version
foreach ($crate in $crates) {
  [void]$text.AppendLine(('{0} {1} ({2}) {3}' -f $crate.name, $crate.version, $crate.license, $crate.repository))
}
foreach ($crate in $crates) {
  $directory = Split-Path -Parent $crate.manifest_path
  $files = @(Get-ChildItem -LiteralPath $directory -File | Where-Object { $_.Name -match '^(LICEN[CS]E|COPYING|NOTICE)' } | Sort-Object Name)
  [void]$text.AppendLine('')
  [void]$text.AppendLine(('=' * 78))
  [void]$text.AppendLine(('{0} {1}, {2}' -f $crate.name, $crate.version, $crate.license))
  [void]$text.AppendLine(('=' * 78))
  if ($files.Count -eq 0) {
    [void]$text.AppendLine(('No licence file in the crate; licence: {0}. Standard texts are in licenses/.' -f $crate.license))
  }
  foreach ($file in $files) {
    [void]$text.AppendLine('')
    [void]$text.AppendLine(('--- {0} ---' -f $file.Name))
    [void]$text.AppendLine((Get-Content -LiteralPath $file.FullName -Raw).TrimEnd())
  }
}
[IO.File]::WriteAllText($Output, $text.ToString(), (New-Object System.Text.UTF8Encoding($false)))
"{0} crates written to {1}" -f @($crates).Count, $Output
